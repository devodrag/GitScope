export type Key = keyof typeof messages
export type Translate = (key: Key) => string
export function translate(key: Key, language: Language): string {
  const [english, russian] = messages[key].split('|')
  return language === 'ru' ? russian ?? english : english
}
export function errorText(code: string, t: Translate) {
  const key = `error_${code}` as Key
  return key in messages ? t(key) : t('unavailable')
}
export const LanguageContext = createContext<Language>('en')
export function useI18n() {
  const language = useContext(LanguageContext)
  const locale = language === 'ru' ? 'ru-RU' : 'en-US'
  return { language, locale, t: (key: Key) => translate(key, language) }
}
